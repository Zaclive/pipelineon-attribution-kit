import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createKitServer } from "../server/app.mjs";

test("HTTP tagged visit → call/form/payment → durable attribution, with auth and replay boundaries", async () => {
  const directory = mkdtempSync(join(tmpdir(), "open-attribution-"));
  const config = { database: join(directory, "test.sqlite"), siteId: "example", name: "Example", writeToken: "w".repeat(40), readToken: "r".repeat(40), publicUrl: "http://localhost:4310", origins: ["https://example.com"] };
  let app = createKitServer(config);
  await new Promise(resolve => app.server.listen(0, "127.0.0.1", resolve));
  let base = `http://127.0.0.1:${app.server.address().port}`;
  const now = Date.now();
  const time = hours => new Date(now + hours * 3600000).toISOString();
  const json = async (path, options) => { const response = await fetch(base + path, options); return { status: response.status, headers: response.headers, body: response.status === 204 ? null : await response.json() }; };
  const post = (path, data, token) => json(path, { method: "POST", headers: { "Content-Type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(data) });
  const visit = { siteId: "example", visitorId: randomUUID(), eventId: randomUUID(), occurredAt: time(-3), url: "https://example.com/?utm_source=google&utm_campaign=roof&email=secret@example.com", referrer: null };
  const collect = data => json("/v1/collect", { method: "POST", headers: { "Content-Type": "application/json", Origin: "https://example.com" }, body: JSON.stringify(data) });
  try {
    assert.equal((await post("/v1/collect", visit, null)).status, 403);
    const first = await collect(visit);
    assert.equal(first.status, 200);
    assert.match(first.body.visitorSessionId, /^[a-f0-9-]{36}$/);
    assert.equal((await collect(visit)).body.duplicate, true);
    assert.equal((await collect({ ...visit, url: "https://example.com/different" })).status, 409);
    assert.equal((await collect({ ...visit, siteId: "another" })).status, 404);
    assert.equal((await collect({ ...visit, eventId: randomUUID(), url: "https://other.example/" })).status, 400);
    const second = await collect({ ...visit, eventId: randomUUID(), occurredAt: time(-2), url: "https://example.com/?utm_source=facebook" });
    assert.equal(second.body.visitorSessionId, first.body.visitorSessionId);
    const event = { externalId: "invoice1", source: "crm", eventType: "payment", occurredAt: time(-1), sourceUpdatedAt: time(-1), outcome: "completed", qualification: "qualified", visitorSessionId: first.body.visitorSessionId, amountMinor: 125050, currency: "USD" };
    assert.equal((await post("/v1/outcomes", event, config.readToken)).status, 401);
    assert.equal((await post("/v1/outcomes", event, config.writeToken)).body.status, "created");
    assert.equal((await post("/v1/outcomes", event, config.writeToken)).body.status, "duplicate");
    assert.equal((await post("/v1/outcomes", { ...event, amountMinor: 100 }, config.writeToken)).status, 409);
    const form = { ...event, externalId: "form1", eventType: "form", amountMinor: null, currency: null, outcome: "received" };
    await post("/v1/outcomes", form, config.writeToken);
    const call = { provider: "callrail", accountId: "company1", callId: "call1", occurredAt: time(-1.5), sourceUpdatedAt: time(-1), status: "answered", visitorSessionId: first.body.visitorSessionId };
    assert.equal((await post("/v1/calls", call, config.writeToken)).body.status, "created");
    assert.equal((await post("/v1/calls", call, config.writeToken)).body.status, "duplicate");
    await collect({ ...visit, eventId: randomUUID(), occurredAt: time(-0.5), url: "https://example.com/?utm_source=after-sale" });
    const params = new URLSearchParams({ from: time(-24), to: time(0), model: "first_touch" });
    assert.equal((await json("/v1/report?" + params, {})).status, 401);
    const read = path => json(path, { headers: { authorization: `Bearer ${config.readToken}` } });
    const report = (await read("/v1/report?" + params)).body;
    assert.equal(report.report.groups[0].source, "Google (unclassified)");
    assert.equal(report.report.totals.outcomes, 3);
    assert.equal(report.report.linkedOutcomes, 3);
    assert.equal(report.report.totals.revenueByCurrency.USD, 125050);
    params.set("model", "last_touch");
    assert.equal((await read("/v1/report?" + params)).body.report.groups[0].source, "facebook");
    assert.equal((await read("/v1/recovery?" + params)).body.browsers.length, 0);
    assert.equal((await read("/v1/export")).body.records.length, 3);
    const correction = { ...event, amountMinor: 9900, sourceUpdatedAt: time(-0.25) };
    assert.equal((await post("/v1/outcomes", correction, config.writeToken)).body.status, "updated");
    assert.equal((await post("/v1/outcomes", event, config.writeToken)).body.status, "stale");
    assert.equal((await read("/v1/report?" + params)).body.report.totals.revenueByCurrency.USD, 9900);
    assert.equal((await post("/v1/outcomes", { ...correction, deleted: true, sourceUpdatedAt: time(-0.1) }, config.writeToken)).body.status, "updated");
    assert.equal((await read("/v1/report?" + params)).body.report.totals.payments, 0);
    assert.equal((await read("/v1/export")).body.records.find(row => row.externalId === "invoice1").deleted, true);
    assert.equal((await post("/v1/outcomes", { ...event, sourceUpdatedAt: time(0) }, config.writeToken)).body.status, "updated");
    const rpc = await post("/mcp", { jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "get_attribution_report", arguments: Object.fromEntries(params) } }, config.readToken);
    assert.equal(rpc.body.result.structuredContent.report.totals.payments, 1);
    assert.equal((await json("/v1/config", { headers: { authorization: `Bearer ${config.readToken}`, Origin: "https://evil.example" } })).status, 403);
    const login = await json("/session", { method: "POST", headers: { "Content-Type": "application/json", Origin: config.publicUrl }, body: JSON.stringify({ token: config.readToken }) });
    assert.equal(login.status, 200);
    assert.match(login.headers.get("set-cookie"), /HttpOnly; SameSite=Strict/);
    assert.equal((await json("/v1/config", { headers: { Cookie: login.headers.get("set-cookie").split(";")[0] } })).status, 200);
    await app.close();
    app = createKitServer(config);
    await new Promise(resolve => app.server.listen(0, "127.0.0.1", resolve));
    base = `http://127.0.0.1:${app.server.address().port}`;
    assert.equal((await read("/v1/report?" + params)).body.report.totals.revenueByCurrency.USD, 125050);
    assert.throws(() => createKitServer({ ...config, siteId: "other" }), /different site/);
  } finally { await app.close(); rmSync(directory, { recursive: true, force: true }); }
});
